// Generates public/offline-manifest.json with the REAL size and SHA-256 of every
// offline runtime asset on disk. This is the single source of truth for the
// DownloadManager: sizes, storage requirements, and integrity checks are never
// hardcoded — they are computed from the files in public/vendor.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outPath = join(root, "public", "offline-manifest.json");
const tsOutPath = join(root, "src", "lib", "offlineRuntime", "generated-manifest.ts");

const ENGINES = {
  cpp: {
    label: "C++ · Clang WASM",
    version: "Clang 8.0.1 (LLVM/LLD) · C++17 standard library",
    bundledWithApp: false,
    installable: true,
    assets: [
      "/vendor/clang/clang",
      "/vendor/clang/lld",
      "/vendor/clang/memfs",
      "/vendor/clang/sysroot.tar",
      "/vendor/clang/shared.js",
      "/vendor/clang/runner.js",
      "/vendor/clang/libgcc-shim.o",
      "/vendor/clang.worker.js",
    ],
  },
  python: {
    label: "Python · Pyodide",
    version: "Pyodide 0.26.4 · Python 3.12.1",
    bundledWithApp: true,
    installable: true,
    assets: [
      "/vendor/pyodide/pyodide.js",
      "/vendor/pyodide/pyodide.asm.js",
      "/vendor/pyodide/pyodide.asm.wasm",
      "/vendor/pyodide/python_stdlib.zip",
      "/vendor/pyodide.worker.js",
    ],
  },
  java: {
    label: "Java · TeaVM",
    version: "TeaVM 0.8.0 · OpenJDK javac + WASM runtime",
    bundledWithApp: false,
    installable: true,
    assets: [
      "/vendor/teavm/compile-classlib-teavm.bin",
      "/vendor/teavm/compiler.wasm",
      "/vendor/teavm/compiler.wasm-runtime.js",
      "/vendor/teavm/runtime-classlib-teavm.bin",
      "/vendor/teavm/java.worker.js",
    ],
  },
};

function sha256File(relPath) {
  const abs = join(root, "public", relPath);
  if (!existsSync(abs)) return null;
  const data = readFileSync(abs);
  return createHash("sha256").update(data).digest("hex");
}

function assetInfo(url) {
  const abs = join(root, "public", url.replace(/^\//, ""));
  return {
    url,
    size: statSync(abs).size,
    sha256: sha256File(url),
  };
}

const manifest = {
  version: 1,
  generatedAt: new Date().toISOString(),
  engines: Object.fromEntries(
    Object.entries(ENGINES).map(([id, def]) => {
      const assets = def.assets
        .map(assetInfo)
        .filter((a) => a.sha256 !== null);
      const totalBytes = assets.reduce((sum, a) => sum + a.size, 0);
      return [id, { ...def, assets, totalBytes }];
    })
  ),
};

writeFileSync(outPath, JSON.stringify(manifest, null, 2));
const tsManifest = { version: manifest.version, engines: manifest.engines };
writeFileSync(
  tsOutPath,
  `// AUTO-GENERATED by scripts/generate-offline-manifest.mjs — DO NOT EDIT.
// Sizes and SHA-256 hashes are computed from the real assets in public/vendor.

export const GENERATED_OFFLINE_MANIFEST: {
  version: number;
  engines: Record<"cpp" | "python" | "java", {
    label: string;
    version: string;
    bundledWithApp: boolean;
    installable: boolean;
    totalBytes: number;
    assets: { url: string; size: number; sha256: string | null }[];
  }>;
} = ${JSON.stringify(tsManifest)};
`
);
console.log(
  "offline-manifest.json written:",
  Object.fromEntries(
    Object.entries(manifest.engines).map(([id, e]) => [id, `${(e.totalBytes / 1048576).toFixed(1)} MB`])
  )
);